def _bind(name, argtypes=None, restype=c_uint32):
    try:
        f = getattr(lib, name)
    except AttributeError:
        def _missing(*a, **k):
            raise NotImplementedError(f"{name} is not exported by the loaded library", [])
        return _missing
    if argtypes is not None:
        f.argtypes = argtypes
    f.restype = restype
    return f

